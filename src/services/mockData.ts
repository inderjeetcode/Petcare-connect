// Helper to create an exact 7-day activated consultation
const createActiveConsultation = (
  id: string,
  daysAgoActivated: number,
  hoursAgoActivated: number,
  doctorId: string,
  petId: string,
  reason: string
): Consultation => {
  const activatedDate = new Date(now.getTime() - (daysAgoActivated * 24 * 60 * 60 * 1000) - (hoursAgoActivated * 60 * 60 * 1000));
  const expiresDate = new Date(activatedDate.getTime() + (7 * 24 * 60 * 60 * 1000));
  const isExpired = expiresDate.getTime() <= now.getTime();

  return {
    id,
    client_id: 'user-client-1',
    doctor_id: doctorId,
    pet_id: petId,
    consultation_reason: reason,
    consultation_status: isExpired ? 'expired' : 'active',
    activated_at: activatedDate.toISOString(),
    expires_at: expiresDate.toISOString(),
    completed_at: null,
    created_at: new Date(activatedDate.getTime() - (2 * 60 * 60 * 1000)).toISOString(),
    updated_at: new Date().toISOString(),
    client_name: 'Sarah Jenkins',
    doctor_name: doctorId === 'doc-1' ? 'Dr. Marcus Vance' : doctorId === 'doc-2' ? 'Dr. Elena Rostova' : 'Dr. Priya Patel',
    doctor_specialization: doctorId === 'doc-1' ? 'Small Animal Orthopedics' : doctorId === 'doc-2' ? 'Feline Internal Medicine' : 'Veterinary Dermatology',
    pet_name: petId === 'pet-1' ? 'Barnaby' : petId === 'pet-2' ? 'Cleo' : 'Pip',
    pet_species: petId === 'pet-1' ? 'Dog' : petId === 'pet-2' ? 'Cat' : 'Bird',
    pet_breed: petId === 'pet-1' ? 'Golden Retriever' : petId === 'pet-2' ? 'Ragdoll' : 'Cockatiel',
  };
};

