// Helper to compute ISO timestamp offsets
const now = new Date();
const daysAgo = (days: number, hours: number = 0) => {
  const d = new Date(now.getTime() - (days * 24 * 60 * 60 * 1000) - (hours * 60 * 60 * 1000));
  return d.toISOString();
};
const daysFromNow = (days: number, hours: number = 0) => {
  const d = new Date(now.getTime() + (days * 24 * 60 * 60 * 1000) + (hours * 60 * 60 * 1000));
  return d.toISOString();
};

